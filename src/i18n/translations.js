export function translate(language, key, values = {}) {
  const message =
    translations[language]?.[key] ?? translations.en[key] ?? key

  return message.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  )
}
